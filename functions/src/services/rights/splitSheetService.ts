/**
 * Split-Sheet Service
 * 
 * Generates split-sheet documents (CSV and PDF) from rights splits
 */

import { logger } from 'firebase-functions';
import { RightsSplit } from '../../../../src/types/export';
import { ReleaseManifest } from '../../../../src/types/export';

/**
 * Generate CSV split-sheet
 */
export function generateCSV(splits: RightsSplit[]): string {
  const headers = ['userId', 'userName', 'sharePercent', 'role', 'contact'];
  const rows = splits.map((split) => [
    split.userId,
    split.name,
    split.percentage.toString(),
    split.role || '',
    '', // Contact would need to be added to RightsSplit type or fetched separately
  ]);

  const csvContent = [
    headers.join(','),
    ...rows.map((row) => row.map((cell) => `"${cell}"`).join(',')),
  ].join('\n');

  return csvContent;
}

